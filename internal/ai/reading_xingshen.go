// 形神层:命宫主星 → 体貌气质速写(一星一句)。
//
// 依据:《紫微斗数全书·形性赋》(公版,语料库在库)为骨,
// 《紫微斗数精成》诸星落命宫章相貌段(研究语料)为肉,义引归纳、行文原创。
// 分寸:形貌受庙陷煞吉与遗传左右,只作「多见之相」的倾向描写,句末留余地。
package ai

import "strings"

// xingShenNote 主星 → 形神速写。
var xingShenNote = map[string]string{
	"紫微": "相貌敦厚、腰背丰隆,天庭饱满、自带威仪,初见觉其高远,熟识方知热忱",
	"天机": "形容清瘦、眉目灵动,书卷气重,举止敏捷,神思常在眼波流转间",
	"太阳": "面方圆而有光彩,气宇轩昂、声朗步阔,人群中自然显眼",
	"武曲": "骨架结实、形小而声高量大,行动干脆利落,一望便是做事之人",
	"天同": "面圆体润、眉清目秀,常带笑意近于童颜,让人不设防",
	"廉贞": "眉宽口阔、颧面有棱,目光锐利,精悍中带三分傲气",
	"天府": "面方圆红润、体态安稳丰腴,雍容有度,坐在那里便是定盘星",
	"太阴": "面皮白净、眉弯目澈,文静清秀,静处时自有一段沉静之美",
	"贪狼": "入庙体丰、落陷形瘦,眉浓目善、神采飞扬,言笑间自带交际的磁场",
	"巨门": "体貌敦实、背厚,面色沉着,开口便见口才,不言时略显严肃",
	"天相": "相貌持重诚恳,衣着整洁讲究,望之可托付之相",
	"天梁": "面方带长者气,眉目清正、老成稳健,年少亦有长者风",
	"七杀": "中高精壮、目大有威、眉如剑势,不怒自威,行路带风",
	"破军": "背厚肩宽、坐立随性,眉宇开阔,豪放不拘小节,动多于静",
}

// xingShenClause 命宫主星(至多二颗)→ 形神句;空则返回空串。
func xingShenClause(majors []string) string {
	var parts []string
	for _, m := range majors {
		if len(parts) >= 2 {
			break
		}
		if n, ok := xingShenNote[m]; ok {
			parts = append(parts, n)
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return "形神多见:" + strings.Join(parts, ";双星同宫者气质相糅,") + "(庙陷煞吉有别,兼看遗传)。"
}
