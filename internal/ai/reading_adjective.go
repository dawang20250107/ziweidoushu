// adjectiveNotes 收集某宫有断语义的杂曜短句(Stars 中的 minor + ExtraStars),
// 至多三条——杂曜是点缀,多则喧宾夺主。
func adjectiveNotes(p *ziwei.Palace, pname string) []string {
	if p == nil {
		return nil
	}
	var notes []string
	scan := func(stars []ziwei.Star) {
		for _, s := range stars {
			if len(notes) >= 3 {
				return
			}
			if s.Type != ziwei.StarMinor {
				continue
			}
			if byPalace, ok := adjectiveClause[s.Name]; ok {
				if clause, ok2 := byPalace[pname]; ok2 {
					notes = append(notes, clause)
				}
			}
		}
	}
	scan(p.Stars)
	scan(p.ExtraStars)
	return notes
}

// adjectiveTail 组装杂曜点缀句(空则返回空串)。
func adjectiveTail(p *ziwei.Palace, pname string) string {
	notes := adjectiveNotes(p, pname)
	if len(notes) == 0 {
		return ""
	}
	return strings.Join(notes, ";") + "。"
}
