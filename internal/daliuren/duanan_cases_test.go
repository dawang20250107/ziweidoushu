package daliuren

// 以书校机:《六壬断案》(邵彦和,研究语料 00bf403d)占例回归。
// 8 例参数完整(日干支/占时/月将/书载三传俱全),独立重排核验后钉死引擎。
// 书中课体用古名(元首/重审/知一),对应本引擎九宗门口径:
// 元首=上克下之贼克、重审=下贼上之贼克、知一=比用。
//
// 两处口径由此批占例修正并锚定:
//   - 案02:第一课克战以日干本气五行论(戊土上酉金无克),非寄宫支五行(巳火克酉金);
//   - 案76:四课皆贼、比者有二(戌午),涉害于比者中径取孟位上神(午临地盘亥),
//     与理法易简「不数深浅先取孟上神」及断案见机式取法两相吻合。

import "testing"

func TestDuanAnCases(t *testing.T) {
	cases := []struct {
		name       string
		stem, brch rune // 日干支
		hour, gen  rune // 占时、月将
		chuan      [3]string
		keType     string // 引擎九宗门口径
		bookLabel  string // 书中课体标名(存照)
	}{
		{"案01 韩太守占祈雪 己卯日寅将酉时", '己', '卯', '酉', '寅', [3]string{"巳", "戌", "卯"}, "比用", "知一/铸印"},
		{"案02 占晴雨 戊申日子将申时", '戊', '申', '申', '子', [3]string{"辰", "申", "子"}, "贼克", "元首/润下"},
		{"案03 州官占雨 癸丑日辰将辰时", '癸', '丑', '辰', '辰', [3]string{"丑", "戌", "未"}, "伏吟", "伏吟/稼穑"},
		{"案04 张九翁占宅 庚寅日辰将未时", '庚', '寅', '未', '辰', [3]string{"巳", "寅", "亥"}, "贼克", "元首/元胎"},
		{"案08 庚辰日午将寅时", '庚', '辰', '寅', '午', [3]string{"辰", "申", "子"}, "贼克", "元首/润下"},
		{"案09 壬寅日丑将申时", '壬', '寅', '申', '丑', [3]string{"子", "巳", "戌"}, "比用", "知一/斩关"},
		{"案10 庚寅日寅将酉时", '庚', '寅', '酉', '寅', [3]string{"子", "巳", "戌"}, "比用", "铸印/知一"},
		{"案76 庚辰日子将巳时", '庚', '辰', '巳', '子', [3]string{"午", "丑", "申"}, "涉害", "涉害/绝嗣"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			r, err := Cast(sIdx(c.stem), bIdx(c.brch), bIdx(c.hour), bIdx(c.gen))
			if err != nil {
				t.Fatal(err)
			}
			if r.Chuan != c.chuan {
				t.Fatalf("三传: got %v want %v(书标%s)", r.Chuan, c.chuan, c.bookLabel)
			}
			if r.KeType != c.keType {
				t.Fatalf("课体: got %s want %s(书标%s)", r.KeType, c.keType, c.bookLabel)
			}
		})
	}
}
